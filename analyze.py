"""Paper material from the results of experiment.py: Table 2 (test accuracy, mean +- std over the test seeds, average
ranks with the Friedman/Nemenyi statistics), Figure 2 (accuracy of each readout in % of the ridge accuracy versus its
training energy relative to the ridge readout), the numbers quoted in the text, the values of Table 1 (FordA) and the
energy estimate of the readouts.
Usage: python analyze.py [results_dir] [out_dir]   (defaults: results, results/paper); results_dir holds the test/*.jsonl
files of experiment.py or, as paper_results/, the results.csv file that experiment.py writes after the test.

Energy per operation, 45 nm (M. Horowitz, ISSCC 2014): fp32 mult 3.7 pJ, fp32 add 0.9 pJ, int8 mult 0.2 pJ,
int32 add 0.1 pJ, 64-bit SRAM read 10 pJ (8 KB), 20 pJ (32 KB), 100 pJ (1 MB) -> E_acc(s) = 10 pJ sqrt(s / 8 KB).
Conventions (favourable to ridge): ridge training = arithmetic only (Gram M D(D+1)/2 + X'Y M D C + Cholesky D^3/6
+ solves C D^2, fp32 MACs); ridge update = recursive least squares, 2 D^2 + 2 C D MACs; ridge inference = C D MACs
+ one read of every weight. WiSARD with hashed RAM nodes (S = 256 16-bit counters per node and class, local 512-B
tables): training M A read-modify-writes (2 accesses + 1 add), update A of them, inference C A reads + C A adds
(+ C A with bleaching). Figure 2: every WiSARD readout with its selected Q and n (A = ceil(D Q / n) RAM nodes) and
hashed tables. Text: W-QG with hashed RAM nodes and n = 32 ('W-QG-h'). Digitization is common to both readouts."""
import os, sys, glob, json, ast
import numpy as np
import pandas as pd
from scipy.stats import friedmanchisquare, rankdata, wilcoxon

RES = sys.argv[1] if len(sys.argv) > 1 else "results"
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(RES, "paper")
os.makedirs(OUT, exist_ok=True)
# benchmarks of the paper (Table 2 order) -> label in the table
META = {"ACSF1": "ACSF1", "FordA": "FordA", "FordB": "FordB", "FreezerRegularTrain": "FreezerRegular",
        "LargeKitchenAppliances": "LargeKitchenApp.", "RefrigerationDevices": "RefrigerationDev.",
        "SemgHandMovementCh2": "SemgHandMov.Ch2", "SyntheticControl": "SynthControl", "Trace": "Trace",
        "TwoPatterns": "TwoPatterns"}
D = 1024
ESN = [("esn|ridge", "Ridge"), ("esn|ridge_q|mm", "R$_{q}$"), ("esn|W-MM", "W-MM"), ("esn|W-QU", "W-QU"),
       ("esn|W-QG", "W-QG")]
RAW = [("raw|W-MM", "W-MM"), ("raw|W-QU", "W-QU"), ("raw|W-QG", "W-QG")]
RANKED = ESN + [(k, "raw " + l) for k, l in RAW]      # Friedman/Nemenyi among all the readouts of Table 2
Q05 = {2: 1.960, 3: 2.343, 4: 2.569, 5: 2.728, 6: 2.850, 7: 2.949, 8: 3.031, 9: 3.102, 10: 3.164}   # Demsar 2006

files = sorted(glob.glob(os.path.join(RES, "test", "*.jsonl")))
if files:
    df = pd.DataFrame([json.loads(l) for f in files for l in open(f)])
else:                                               # results.csv written by experiment.py (e.g. paper_results/)
    df = pd.read_csv(os.path.join(RES, "results.csv"))
    df["params"] = df.params.apply(ast.literal_eval)
    df["cfg"] = df.cfg_id.apply(lambda i: None if pd.isna(i) else {"id": int(i)})
g = df.groupby(["dataset", "key"]).acc
MEAN, STD, N = g.mean().unstack(), g.std(ddof=0).unstack(), g.size().unstack()
NMAX = int(np.nanmax(N.values))
dss = [d for d in META if d in N.index and (N.loc[d].fillna(0) == NMAX).all()]   # complete benchmarks only
print("complete benchmarks:", dss, "| incomplete:", [d for d in META if d in N.index and d not in dss])
S = {"datasets": dss, "n_seeds": NMAX}

# ------------------------------------------------------------------ average ranks (Friedman/Nemenyi)
A_ = np.array([[MEAN.loc[ds, k] for k, _ in RANKED] for ds in dss])
avg = np.array([rankdata(-row) for row in A_]).mean(0)          # rank 1 = best, ties averaged
AVG = {k: float(r) for (k, _), r in zip(RANKED, avg)}
k_, n_ = len(RANKED), len(dss)
cd = Q05[k_] * np.sqrt(k_ * (k_ + 1) / (6.0 * n_))
fr = friedmanchisquare(*A_.T)
order = np.argsort(avg)
cliques = []
for i in range(k_):
    j = max(jj for jj in range(i, k_) if avg[order[jj]] - avg[order[i]] < cd)
    if j > i and not any(a <= i and j <= b for a, b in cliques):
        cliques.append((i, j))
S["friedman"] = dict(methods=[l for _, l in RANKED], avg_ranks=[round(float(r), 3) for r in avg],
                     chi2=round(float(fr.statistic), 3), p=float(fr.pvalue), cd=round(float(cd), 3), k=k_, N=n_,
                     cliques=[[RANKED[order[t]][1] for t in range(a, b + 1)] for a, b in cliques])

# ------------------------------------------------------------------ Table 2
def tex_p(p):
    if p >= 1e-3:
        return f"{p:.3f}"
    m, e = f"{p:.1e}".split("e")
    return f"{m} \\cdot 10^{{{int(e)}}}"

cell = lambda ds, k: f"{MEAN.loc[ds, k]:.1f}{{\\tiny$\\pm${STD.loc[ds, k]:.1f}}}"
T = [f"% Table 2, generated by analyze.py ({n_} benchmarks, N_h = 1024, mean state, {NMAX} test seeds).",
     r"\begin{table}[t]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{2pt}", r"\renewcommand{\arraystretch}{0.92}",
     r"\begin{tabular}{l|" + "r" * len(ESN) + "|" + "r" * len(RAW) + "}",
     r" & \multicolumn{%d}{c|}{ESN, $N_h = 1024$, mean state} & \multicolumn{%d}{c}{no reservoir}\\" % (len(ESN), len(RAW)),
     r"\textbf{Benchmark} & " + " & ".join(l for _, l in ESN + RAW) + r"\\", r"\hline"]
T += [f"{META[ds]} & " + " & ".join(cell(ds, k) for k, _ in ESN + RAW) + r"\\" for ds in dss]
T += [r"\hline", r"mean & " + " & ".join(f"{MEAN.loc[dss, k].mean():.1f}" for k, _ in ESN + RAW) + r"\\",
      r"avg.\ rank & " + " & ".join(f"{AVG[k]:.2f}" for k, _ in ESN + RAW) + r"\\", r"\end{tabular}", r"\vspace{-1mm}",
      r"\caption{\footnotesize Test accuracy (\%%, mean $\pm$ standard deviation over %d seeds) of the readouts on the reservoir states and on the raw series (R$_q$: ridge readout on quantized states, uniform quantizer). Avg.\ rank: 1 = best; Friedman $p = %s$, Nemenyi critical difference %.2f at $\alpha = 0.05$.}" % (NMAX, tex_p(fr.pvalue), cd),
      r"\label{tab.results}", r"\vspace{-4mm}", r"\end{table}"]
open(os.path.join(OUT, "tab_results.tex"), "w").write("\n".join(T) + "\n")

# ------------------------------------------------------------------ numbers quoted in the text
keys = list(MEAN.columns)
S["mean_acc"] = {k: round(float(MEAN.loc[dss, k].mean()), 2) for k in keys}
S["per_dataset"] = {ds: {k: [round(float(MEAN.loc[ds, k]), 2), round(float(STD.loc[ds, k]), 2)] for k in keys} for ds in dss}

def paired(a, b):
    x, y = MEAN.loc[dss, a].values, MEAN.loc[dss, b].values
    try:
        p = float(wilcoxon(x, y).pvalue)
    except ValueError:
        p = float("nan")
    return dict(diff=round(float(np.mean(x - y)), 2), wins=int((x > y).sum()), ties=int((x == y).sum()),
                losses=int((x < y).sum()), p_wilcoxon=round(p, 4),
                per_dataset={ds: round(float(MEAN.loc[ds, a] - MEAN.loc[ds, b]), 2) for ds in dss})

W3 = ["W-MM", "W-QU", "W-QG"]
S["esn_minus_raw"] = {w: paired(f"esn|{w}", f"raw|{w}") for w in W3}      # reservoir vs raw series (WiSARD)
S["ridge_minus_W"] = {w: paired("esn|ridge", f"esn|{w}") for w in W3}     # ridge vs ESN-WiSARD
for q in ("mm", "qu"):                                                    # ridge on quantized states
    if f"esn|ridge_q|{q}" in MEAN:
        S[f"ridge_minus_ridge_q_{q}"] = paired("esn|ridge", f"esn|ridge_q|{q}")
S["selected_b"] = {ds: {q: df[(df.dataset == ds) & (df.key == f"esn|ridge_q|{q}")].params.iloc[0].get("b") for q in ("mm", "qu")} for ds in dss}
if "esn|W-QG-h" in MEAN:
    S["WQG_minus_WQGh"] = paired("esn|W-QG", "esn|W-QG-h")
S["selected"] = {ds: {k: dict(cfg=(lambda c: None if c is None else {kk: c[kk] for kk in ("id", "sr", "input_scaling", "lr", "bias") if kk in c})(df[(df.dataset == ds) & (df.key == k)].cfg.iloc[0]),
                              params=df[(df.dataset == ds) & (df.key == k)].params.iloc[0])
                     for k in ["esn|ridge", "esn|W-MM", "esn|W-QU", "esn|W-QG", "esn|W-QG-h"] if k in MEAN} for ds in dss}

# ------------------------------------------------------------------ energy
FM, FA, IM8, IA32 = 3.7, 0.9, 0.2, 0.1
e_acc = lambda nbytes: 10.0 * np.sqrt(nbytes / 8192.0)
NODE = 256 * 2                                      # bytes of a hashed RAM node (S = 256 16-bit counters)
gm = lambda v: float(np.exp(np.mean(np.log(v))))
ridge_train = lambda M, C: (M * D * (D + 1) / 2 + M * D * C + D ** 3 / 6 + C * D ** 2) * (FM + FA)   # pJ
hashed_train = lambda M, A: M * A * (2 * e_acc(NODE) + IA32)                                         # pJ

# Figure 2: accuracy in % of the ridge accuracy (mean, interquartile range) vs training energy relative to the ridge
pts = []
for ds in dss:
    r = df[(df.dataset == ds) & (df.key == "esn|ridge")].iloc[0]
    C, M = int(r.C), int(r.n_train)
    for k, _ in ESN:
        h = df[(df.dataset == ds) & (df.key == k)].iloc[0]
        e = hashed_train(M, int(h.n_rams)) / ridge_train(M, C) if k.startswith("esn|W") else 1.0
        pts.append(dict(ds=ds, key=k, acc_rel=100 * MEAN.loc[ds, k] / MEAN.loc[ds, "esn|ridge"], e_rel=e))
P = pd.DataFrame(pts)
S["fig2"] = {}
for k, _ in ESN:
    x = P[P.key == k]
    S["fig2"][k] = dict(acc_mean=round(float(x.acc_rel.mean()), 2), acc_iqr=np.percentile(x.acc_rel, [25, 75]).round(2).tolist(),
                        e_gm=gm(x.e_rel.values), ridge_over_e_gm=round(1 / gm(x.e_rel.values)))
STY = {"esn|ridge": ("cRidge", "*", "", "Ridge"), "esn|ridge_q|mm": ("cRq", "square*", "", "R$_q$"),
       "esn|W-MM": ("cWMM", "triangle*", "", "W-MM"), "esn|W-QU": ("cWQU", "triangle*", ", rotate=180", "W-QU"),
       "esn|W-QG": ("cWQG", "diamond*", "", "W-QG")}
F = [f"% Figure 2, generated by analyze.py: accuracy in % of the ridge accuracy (mean over the {n_} benchmarks, bars = interquartile range)",
     "% vs training energy relative to the ridge readout (geometric mean; WiSARD readouts with hashed RAM nodes of 256 counters).",
     r"\definecolor{cRidge}{HTML}{2A78D6}\definecolor{cRq}{HTML}{EB6834}\definecolor{cWMM}{HTML}{1BAF7A}\definecolor{cWQU}{HTML}{EDA100}\definecolor{cWQG}{HTML}{E87BA4}",
     r"\begin{tikzpicture}",
     r"\begin{axis}[width=5.3cm, height=2.12cm, scale only axis, xmode=log, xmin=3e-4, xmax=3, ymin=88, ymax=101.5,",
     r"  xtick={0.001,0.01,0.1,1}, xticklabels={$10^{-3}$,$10^{-2}$,$10^{-1}$,$1$}, ytick={90,95,100},",
     r"  xlabel={training energy relative to the ridge readout}, ylabel={accuracy\\(\% of ridge)}, ylabel style={align=center},",
     r"  label style={font=\scriptsize}, tick label style={font=\scriptsize}, xlabel shift=-3pt, ylabel shift=-3pt,",
     r"  grid=major, grid style={line width=0.3pt, draw=black!12}, axis line style={line width=0.4pt},",
     r"  legend style={font=\scriptsize, draw=none, fill=none, at={(0.5,0.04)}, anchor=south, legend columns=2, /tikz/every even column/.append style={column sep=6pt}},",
     r"  legend cell align=left]"]
for k, _ in ESN:
    c, mk, opt, lab = STY[k]
    f2 = S["fig2"][k]
    y, (q1, q3) = f2["acc_mean"], f2["acc_iqr"]
    ms = "2.4pt" if mk in ("*", "square*") else "3pt"
    mo = f"mark options={{fill={c}, draw=white, line width=0.4pt, mark size={ms}{opt}}}"
    if k == "esn|ridge":
        F.append(f"\\addplot[only marks, color={c}, mark={mk}, {mo}] coordinates {{(1.0, 100.0)}};")
    else:
        F.append(f"\\addplot[only marks, color={c}, mark={mk}, {mo}, error bars/.cd, y dir=both, y explicit, error bar style={{line width=0.6pt, color={c}}}, error mark options={{rotate=90, mark size=1.5pt, color={c}}}] coordinates {{({f2['e_gm']:.4g}, {y:.2f}) -= (0, {y - q1:.2f}) += (0, {q3 - y:.2f})}};")
    F.append(f"\\addlegendentry{{{lab}}}")
F += [r"\end{axis}", r"\end{tikzpicture}"]
open(os.path.join(OUT, "fig_tradeoff.tex"), "w").write("\n".join(F) + "\n")

# text: W-QG with hashed RAM nodes and n = 32 (training, exact update, inference, memory)
rows = []
for ds in dss:
    rid = df[(df.dataset == ds) & (df.key == "esn|ridge")].iloc[0]
    h = df[(df.dataset == ds) & (df.key == "esn|W-QG-h")]
    if not len(h):
        continue
    h = h.iloc[0]
    C, M = int(rid.C), int(rid.n_train)
    A, bl = int(h.n_rams), int(h.params["bl"])
    tot = C * A * NODE
    r = dict(dataset=ds, C=C, M=M, A=A, Q=int(h.params["Q"]), bl=bl, acc_ridge=MEAN.loc[ds, "esn|ridge"],
             acc_wqgh=MEAN.loc[ds, "esn|W-QG-h"], mem_ridge_model_kb=4 * C * D / 1024,
             mem_ridge_train_kb=(4 * D * D + 4 * C * D) / 1024, mem_wqgh_kb=tot / 1024)
    r["E_inf_ridge_fp32_nJ"] = (C * D * (FM + FA) + C * D / 2 * e_acc(4 * C * D)) / 1e3
    r["E_inf_ridge_int8_nJ"] = (C * D * (IM8 + IA32) + C * D / 8 * e_acc(C * D)) / 1e3
    r["E_train_ridge_uJ"] = ridge_train(M, C) / 1e6
    r["E_upd_ridge_nJ"] = (2 * D * D + 2 * C * D) * (FM + FA) / 1e3
    for name, sz in (("local", NODE), ("single", tot)):
        r[f"E_inf_wqgh_{name}_nJ"] = C * A * (e_acc(sz) + IA32 * (1 + bl)) / 1e3
        r[f"E_train_wqgh_{name}_uJ"] = M * A * (2 * e_acc(sz) + IA32) / 1e6
        r[f"E_upd_wqgh_{name}_nJ"] = A * (2 * e_acc(sz) + IA32) / 1e3
    rows.append(r)
if rows:
    E = pd.DataFrame(rows)
    E.to_csv(os.path.join(OUT, "energy_estimates.csv"), index=False)
    S["energy_ratios_gm_min_max"] = {}
    for lab, num, den in [("inference fp32 / local", "E_inf_ridge_fp32_nJ", "E_inf_wqgh_local_nJ"),
                          ("inference int8 / local", "E_inf_ridge_int8_nJ", "E_inf_wqgh_local_nJ"),
                          ("inference fp32 / single", "E_inf_ridge_fp32_nJ", "E_inf_wqgh_single_nJ"),
                          ("training / local", "E_train_ridge_uJ", "E_train_wqgh_local_uJ"),
                          ("training / single", "E_train_ridge_uJ", "E_train_wqgh_single_uJ"),
                          ("update / local", "E_upd_ridge_nJ", "E_upd_wqgh_local_nJ"),
                          ("update / single", "E_upd_ridge_nJ", "E_upd_wqgh_single_nJ"),
                          ("memory model ridge / W-QG-h", "mem_ridge_model_kb", "mem_wqgh_kb")]:
        v = E[num] / E[den]
        S["energy_ratios_gm_min_max"][lab] = [round(gm(v), 3), round(float(v.min()), 3), round(float(v.max()), 3)]
    S["energy_per_dataset"] = {r["dataset"]: {k: (round(v, 4) if isinstance(v, float) else v) for k, v in r.items() if k != "dataset"} for r in rows}

# ------------------------------------------------------------------ Table 1 (values for FordA)
cost = {}
for ds in dss:
    w = df[(df.dataset == ds) & (df.key == "esn|W-QG")].iloc[0]
    C, M = int(w.C), int(w.n_train)
    A, n = int(w.n_rams), int(w.params["n"])
    cost[ds] = dict(C=C, M=M, Q=int(w.params["Q"]), n=n, A=A, U=int(w.n_entries), mem_sparse_kb=round(float(w.mem_kb_sparse), 1),
                    ridge_train_flops=M * D ** 2 + D ** 3 / 3, ridge_update_macs=2 * D ** 2, ridge_inf_macs=C * D,
                    ridge_mem_train_kb=32 * D * (D + C) / 8 / 1024, ridge_mem_model_kb=32 * C * D / 8 / 1024,
                    w_train_incr=M * A, w_update_incr=A, w_inf_lookups=C * A)
S["cost_table"] = cost
json.dump(S, open(os.path.join(OUT, "summary.json"), "w"), indent=1, default=str)
pd.set_option("display.width", 250); pd.set_option("display.max_columns", 40)
print((MEAN.loc[dss].T.round(1)).to_string())
print(json.dumps({k: v for k, v in S.items() if k not in ("per_dataset", "selected", "energy_per_dataset", "cost_table")}, indent=1, default=str))
